begin;

create type public.track_key as enum ('se', 'ai', 'data', 'math', 'stats');
create type public.task_status as enum ('todo', 'doing', 'done');

create table public.tasks (
  id uuid primary key default gen_random_uuid(),
  track public.track_key not null,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  note text check (note is null or char_length(note) <= 10000),
  status public.task_status not null default 'todo',
  due_date date,
  sort_order bigint generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  done_at timestamptz,
  archived_at timestamptz,
  constraint tasks_done_at_consistent check (
    (status = 'done' and done_at is not null)
    or (status <> 'done' and done_at is null)
  )
);

create index tasks_active_order_idx
  on public.tasks (track, status, sort_order desc, created_at desc, id)
  where archived_at is null;

create function public.set_task_timestamps()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.title := btrim(new.title);
  new.updated_at := now();
  if new.status = 'done' then
    if TG_OP = 'INSERT' then
      new.done_at := now();
    elsif old.status <> 'done' then
      new.done_at := now();
    else
      new.done_at := old.done_at;
    end if;
  else
    new.done_at := null;
  end if;
  return new;
end;
$$;

create trigger tasks_timestamps
before insert or update on public.tasks
for each row execute function public.set_task_timestamps();

create table public.login_attempts (
  id bigint generated always as identity primary key,
  ip_hash text not null check (ip_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now()
);

create index login_attempts_ip_time_idx
  on public.login_attempts (ip_hash, created_at);
create index login_attempts_cleanup_idx
  on public.login_attempts (created_at);

-- Atomic attempt reservation for requests from the same IP.
create function public.reserve_login_attempt(p_ip_hash text)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_now timestamptz;
  v_count bigint;
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_ip_hash, 0)
  );
  v_now := clock_timestamp();

  select count(*) into v_count
  from public.login_attempts
  where ip_hash = p_ip_hash
    and created_at > v_now - interval '15 minutes';

  if v_count >= 5 then
    return false;
  end if;

  insert into public.login_attempts (ip_hash, created_at)
  values (p_ip_hash, v_now);
  return true;
end;
$$;

alter table public.tasks enable row level security;
alter table public.login_attempts enable row level security;

revoke all on public.tasks, public.login_attempts
  from public, anon, authenticated;
revoke all on sequence public.tasks_sort_order_seq,
  public.login_attempts_id_seq from public, anon, authenticated;
revoke all on function public.set_task_timestamps()
  from public, anon, authenticated;
revoke all on function public.reserve_login_attempt(text)
  from public, anon, authenticated;

grant usage on schema public to service_role;
grant usage on type public.track_key, public.task_status to service_role;
grant select, insert, update on public.tasks to service_role;
grant select, insert, delete on public.login_attempts to service_role;
grant usage, select on sequence public.tasks_sort_order_seq,
  public.login_attempts_id_seq to service_role;
grant execute on function public.reserve_login_attempt(text)
  to service_role;

commit;
