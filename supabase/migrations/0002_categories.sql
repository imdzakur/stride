-- supabase/migrations/0002_categories.sql
begin;

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  track public.track_key not null,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  sort_order bigint generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  constraint categories_id_track_unique unique (id, track)
);

create unique index categories_active_name_unique
  on public.categories (track, lower(btrim(name)))
  where archived_at is null;
create index categories_active_order_idx
  on public.categories (track, sort_order, name, id)
  where archived_at is null;

alter table public.tasks add column category_id uuid;
alter table public.tasks add constraint tasks_category_track_fk
  foreign key (category_id, track)
  references public.categories (id, track)
  on update restrict on delete restrict;

create index tasks_active_category_idx
  on public.tasks (category_id, track, status)
  where archived_at is null;

create function public.validate_category_change()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.name := btrim(new.name);
  new.updated_at := now();

  if TG_OP = 'UPDATE' then
    if new.track is distinct from old.track then
      raise exception 'category_track_immutable' using errcode = '23514';
    end if;

    if old.archived_at is null and new.archived_at is not null then
      if exists (
        select 1 from public.tasks
        where category_id = old.id and archived_at is null
      ) then
        raise exception 'category_has_active_tasks' using errcode = '23514';
      end if;
    end if;
  end if;

  return new;
end;
$$;

create trigger categories_validate_change
before insert or update on public.categories
for each row execute function public.validate_category_change();

create function public.validate_task_category()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.archived_at is null and new.category_id is not null then
    -- Lock the category for the transaction so assignment and archiving cannot interleave.
    perform 1 from public.categories
    where id = new.category_id
      and track = new.track
      and archived_at is null
    for share;

    if not found then
      raise exception 'active_category_required' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

create trigger tasks_validate_category
before insert or update of category_id, track, archived_at on public.tasks
for each row execute function public.validate_task_category();

alter table public.categories enable row level security;
revoke all on public.categories from public, anon, authenticated;
revoke all on sequence public.categories_sort_order_seq
  from public, anon, authenticated;
revoke all on function public.validate_category_change()
  from public, anon, authenticated;
revoke all on function public.validate_task_category()
  from public, anon, authenticated;

grant select, insert, update on public.categories to service_role;
grant usage, select on sequence public.categories_sort_order_seq
  to service_role;

commit;
