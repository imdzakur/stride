-- supabase/migrations/0004_checklists.sql
-- Replaces categories with per-task checklists.
-- Run once after 0001, 0002, and 0003. It permanently drops the categories table
-- and tasks.category_id; tasks themselves are kept.
begin;

-- 1. Remove categories and everything that depends on them.
drop trigger if exists tasks_validate_category on public.tasks;
drop function if exists public.validate_task_category();
alter table public.tasks drop constraint if exists tasks_category_track_fk;
drop index if exists public.tasks_active_category_idx;
alter table public.tasks drop column if exists category_id;

drop trigger if exists categories_validate_change on public.categories;
drop function if exists public.validate_category_change();
drop table if exists public.categories;

-- The old progress function reads categories, so it is replaced below.
drop function if exists public.get_progress();

-- 2. Checklist items (steps) inside a task.
create table public.task_items (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks (id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  done boolean not null default false,
  sort_order bigint generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  done_at timestamptz,
  constraint task_items_done_at_consistent check (
    (done and done_at is not null) or (not done and done_at is null)
  )
);

create index task_items_task_order_idx
  on public.task_items (task_id, sort_order, id);

-- Status a task should have from its checklist; null when it has no items.
create function public.derive_task_status(p_task_id uuid)
returns public.task_status
language sql
stable
security invoker
set search_path = ''
as $$
  select case
    when count(*) = 0 then null
    when count(*) filter (where i.done) = count(*) then 'done'::public.task_status
    when count(*) filter (where i.done) > 0 then 'doing'::public.task_status
    else 'todo'::public.task_status
  end
  from public.task_items i
  where i.task_id = p_task_id;
$$;

-- Keeps item fields consistent and only allows items on active tasks.
create function public.set_task_item_fields()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.title := btrim(new.title);
  new.updated_at := now();

  if TG_OP = 'UPDATE' and new.task_id is distinct from old.task_id then
    raise exception 'task_item_task_immutable' using errcode = '23514';
  end if;

  if new.done then
    if TG_OP = 'INSERT' or not old.done then
      new.done_at := now();
    else
      new.done_at := old.done_at;
    end if;
  else
    new.done_at := null;
  end if;

  -- Lock the parent so concurrent item changes and archiving cannot interleave.
  perform 1 from public.tasks
  where id = new.task_id and archived_at is null
  for update;

  if not found then
    raise exception 'active_task_required' using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger task_items_fields
before insert or update on public.task_items
for each row execute function public.set_task_item_fields();

-- Any change to the checklist recalculates the parent status.
create function public.sync_task_status_from_items()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_task_id uuid;
begin
  v_task_id := case when TG_OP = 'DELETE' then old.task_id else new.task_id end;
  update public.tasks
  set status = coalesce(public.derive_task_status(v_task_id), status)
  where id = v_task_id;
  return null;
end;
$$;

create trigger task_items_sync_status
after insert or update of done or delete on public.task_items
for each row execute function public.sync_task_status_from_items();

-- A task with a checklist always carries the derived status, whatever the client sends.
-- The trigger name sorts before tasks_timestamps, so done_at is set from the final status.
create function public.apply_derived_task_status()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_status public.task_status;
begin
  v_status := public.derive_task_status(new.id);
  if v_status is not null then
    new.status := v_status;
  end if;
  return new;
end;
$$;

create trigger tasks_derive_status
before update on public.tasks
for each row execute function public.apply_derived_task_status();

-- 3. Create a task with its first checklist items in one transaction.
create function public.create_task_with_items(
  p_track public.track_key,
  p_title text,
  p_note text,
  p_due_date date,
  p_items text[]
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id uuid;
begin
  insert into public.tasks (track, title, note, due_date)
  values (p_track, p_title, p_note, p_due_date)
  returning id into v_id;

  if p_items is not null and pg_catalog.cardinality(p_items) > 0 then
    insert into public.task_items (task_id, title)
    select v_id, x.item
    from pg_catalog.unnest(p_items) with ordinality as x(item, ord)
    order by x.ord;
  end if;

  return v_id;
end;
$$;

-- 4. Progress per track in one statement.
-- A task with a checklist counts each item as one step; a task without one counts as one step.
create function public.get_progress()
returns table (
  track public.track_key,
  total bigint,
  todo_count bigint,
  doing_count bigint,
  done_count bigint,
  step_total bigint,
  step_done bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with track_keys as (
    select k.track
    from pg_catalog.unnest(pg_catalog.enum_range(null::public.track_key)) as k(track)
  ),
  item_counts as (
    select i.task_id,
      count(*) as item_total,
      count(*) filter (where i.done) as item_done
    from public.task_items i
    group by i.task_id
  ),
  task_steps as (
    select t.track, t.status,
      case when c.item_total > 0 then c.item_total else 1 end as steps,
      case
        when c.item_total > 0 then c.item_done
        when t.status = 'done' then 1
        else 0
      end as steps_done
    from public.tasks t
    left join item_counts c on c.task_id = t.id
    where t.archived_at is null
  )
  select
    tk.track,
    count(s.status) as total,
    count(s.status) filter (where s.status = 'todo') as todo_count,
    count(s.status) filter (where s.status = 'doing') as doing_count,
    count(s.status) filter (where s.status = 'done') as done_count,
    coalesce(sum(s.steps), 0)::bigint as step_total,
    coalesce(sum(s.steps_done), 0)::bigint as step_done
  from track_keys tk
  left join task_steps s on s.track = tk.track
  group by tk.track
  order by tk.track;
$$;

-- 5. Security: RLS without public policies, backend-only grants.
alter table public.task_items enable row level security;

revoke all on public.task_items from public, anon, authenticated;
revoke all on sequence public.task_items_sort_order_seq from public, anon, authenticated;
revoke all on function public.derive_task_status(uuid) from public, anon, authenticated;
revoke all on function public.set_task_item_fields() from public, anon, authenticated;
revoke all on function public.sync_task_status_from_items() from public, anon, authenticated;
revoke all on function public.apply_derived_task_status() from public, anon, authenticated;
revoke all on function public.create_task_with_items(public.track_key, text, text, date, text[])
  from public, anon, authenticated;
revoke all on function public.get_progress() from public, anon, authenticated;

grant select, insert, update, delete on public.task_items to service_role;
grant usage, select on sequence public.task_items_sort_order_seq to service_role;
grant execute on function public.derive_task_status(uuid) to service_role;
grant execute on function public.create_task_with_items(public.track_key, text, text, date, text[])
  to service_role;
grant execute on function public.get_progress() to service_role;

commit;
